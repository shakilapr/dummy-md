"""The research inventory as machine-readable data.

Every generation target from the Markdown feature survey appears exactly once.
``implemented`` is the honesty flag: a feature is selectable only when the engine
can actually emit it, and a test exercises every implemented feature end to end.
"""

from __future__ import annotations

from dataclasses import replace

from dummy_md.core.features import FeatureSpec

# Dialect sets. CommonMark is the base every dialect speaks.
C = frozenset({"commonmark", "gfm", "extended", "stress"})
G = frozenset({"gfm", "extended", "stress"})
E = frozenset({"extended", "stress"})
S = frozenset({"stress"})


# Families that are emitted through a shared generator.
_FAMILY_GENERATORS: dict[str, str] = {
    "meta": "frontmatter",
}


def F(
    feature_id: str,
    kind: str,
    dialects: frozenset[str],
    tier: str,
    *,
    requires: tuple[str, ...] = (),
    implemented: bool = False,
    generator: str | None = None,
    implicit: bool = False,
    weight: float = 1.0,
) -> FeatureSpec:
    """Build a catalog entry.

    ``generator`` defaults to the family name; ``implicit`` marks features that
    are not produced by any generator (the document body itself).
    """
    family = feature_id.split(".")[0]
    return FeatureSpec(
        id=feature_id,
        family=family,
        kind=kind,
        dialects=dialects,
        tier=tier,
        generator=None
        if implicit
        else (generator or _FAMILY_GENERATORS.get(family, family)),
        requires=frozenset(requires),
        default_weight=weight,
        implemented=implemented,
    )


